export function getAllWikiBrands(): string[] {
  const brands = new Set<string>();
  for (const item of PRINTER_WIKI_DATABASE) {
    brands.add(item.brand);
  }
  return Array.from(brands).sort();
}

export function getWikiModelsByBrand(brand: string): PrinterWikiModel[] {
  const cleanBrand = brand.trim().toLowerCase();
  return PRINTER_WIKI_DATABASE.filter((item) => item.brand.toLowerCase() === cleanBrand);
}

export function findWikiModel(
  brand?: string | null,
  model?: string | null,
): PrinterWikiModel | undefined {
  if (!brand && !model) return undefined;
  const b = (brand || "").trim().toLowerCase();
  const m = (model || "").trim().toLowerCase();

  // Busca exata
  const exact = PRINTER_WIKI_DATABASE.find(
    (item) => item.brand.toLowerCase() === b && item.model.toLowerCase() === m,
  );
  if (exact) return exact;

  // Busca por proximidade de modelo
  if (m) {
    const byModel = PRINTER_WIKI_DATABASE.find((item) => {
      const itemMod = item.model.toLowerCase();
      return (
        itemMod.includes(m) ||
        m.includes(itemMod) ||
        (item.brand.toLowerCase() === b && (itemMod.includes(m) || m.includes(itemMod)))
      );
    });
    if (byModel) return byModel;
  }

  // Busca com keywords comuns (ex.: "x1c", "p1s", "a1", "k1c", "mk4", "sv08")
  const norm = `${b} ${m}`.toLowerCase().replace(/[^a-z0-9]/g, "");
  return PRINTER_WIKI_DATABASE.find((item) => {
    const itemNorm = `${item.brand} ${item.model}`.toLowerCase().replace(/[^a-z0-9]/g, "");
    return norm.includes(itemNorm) || itemNorm.includes(norm);
  });
}

export function searchWiki(query: string): PrinterWikiModel[] {
  const q = query.trim().toLowerCase();
  if (!q) return PRINTER_WIKI_DATABASE;
  return PRINTER_WIKI_DATABASE.filter(
    (item) =>
      item.brand.toLowerCase().includes(q) ||
      item.model.toLowerCase().includes(q) ||
      item.technology.toLowerCase().includes(q) ||
      item.compatibleMaterials.some((mat) => mat.toLowerCase().includes(q)),
  );
}
